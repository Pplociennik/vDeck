package com.github.pplociennik.vdeck.feature.releasenotes.service.impl;

import com.github.pplociennik.vdeck.feature.releasenotes.domain.ReleaseNotes;
import com.github.pplociennik.vdeck.feature.releasenotes.domain.ReleaseNotesAcknowledgement;
import com.github.pplociennik.vdeck.feature.releasenotes.exc.ReleaseNotesException;
import com.github.pplociennik.vdeck.feature.releasenotes.persistence.ReleaseNotesAcknowledgementRepository;
import com.github.pplociennik.vdeck.feature.releasenotes.service.ReleaseNotesService;
import com.github.pplociennik.vdeck.runtime.installation.ReleaseVersion;
import jakarta.annotation.Nonnull;
import jakarta.annotation.Nullable;
import lombok.extern.log4j.Log4j2;
import org.springframework.boot.info.BuildProperties;
import org.springframework.dao.DataAccessException;
import org.springframework.stereotype.Service;

import java.util.Comparator;
import java.util.List;
import java.util.Optional;

import static java.util.Objects.requireNonNull;

/**
 * Selects the change lists to show from the files read by {@link ReleaseNotesReader} and the
 * acknowledgements stored in the panel database.
 *
 * <p>The installed version is resolved once, from {@link BuildProperties} generated by the Maven build.
 * Without it - for example when the panel runs from an IDE that did not run the build - the feature is
 * off and the panel never shows a change list.
 */
@Log4j2
@Service
class ReleaseNotesServiceImpl implements ReleaseNotesService {

    /**
     * Suffix of a development build version, removed so a development build shows the change list of the
     * version in progress.
     */
    private static final String SNAPSHOT_SUFFIX = "-SNAPSHOT";

    private final ReleaseNotesAcknowledgementRepository acknowledgementRepository;

    private final ReleaseNotesReader releaseNotesReader;

    /**
     * Installed panel version, or {@code null} when it is unknown and the feature is off.
     */
    private final @Nullable ReleaseVersion installedVersion;

    /**
     * Creates the service and resolves the installed version.
     *
     * @param acknowledgementRepository
     *         store of acknowledged versions
     * @param releaseNotesReader
     *         reader of the change list files
     * @param buildProperties
     *         build information of the panel, or {@code null} when the build did not generate it
     * @throws NullPointerException
     *         if the repository or the reader is {@code null}
     */
    ReleaseNotesServiceImpl( @Nonnull ReleaseNotesAcknowledgementRepository acknowledgementRepository,
                             @Nonnull ReleaseNotesReader releaseNotesReader,
                             @Nullable BuildProperties buildProperties ) {
        this.acknowledgementRepository = requireNonNull( acknowledgementRepository,
                "acknowledgementRepository must not be null" );
        this.releaseNotesReader = requireNonNull( releaseNotesReader, "releaseNotesReader must not be null" );
        this.installedVersion = resolveInstalledVersion( buildProperties );
    }

    /** {@inheritDoc} */
    @Override
    public @Nonnull List< ReleaseNotes > findUnacknowledged() {
        if ( installedVersion == null || acknowledgementRepository.existsById( installedVersion.toString() ) ) {
            return List.of();
        }

        ReleaseVersion lastAcknowledged = findLastAcknowledged();
        List< ReleaseNotes > unacknowledged = releaseNotesReader.readAll().stream()
                .filter( releaseNotes -> isUnacknowledged( releaseNotes.version(), lastAcknowledged ) )
                .filter( releaseNotes -> !releaseNotes.sections().isEmpty() )
                .toList();
        log.debug( "Release notes of {} versions wait for acknowledgement of {}, last acknowledged {}",
                unacknowledged.size(), installedVersion, lastAcknowledged );
        return unacknowledged;
    }

    /** {@inheritDoc} */
    @Override
    public void acknowledgeInstalled() {
        if ( installedVersion == null ) {
            log.debug( "Installed version is unknown; no release notes acknowledgement is stored" );
            return;
        }

        try {
            acknowledgementRepository.save( new ReleaseNotesAcknowledgement( installedVersion ) );
        } catch ( DataAccessException exception ) {
            throw ReleaseNotesException.acknowledgementFailed( exception );
        }
        log.info( "Release notes of version {} acknowledged", installedVersion );
    }

    private static @Nullable ReleaseVersion resolveInstalledVersion( @Nullable BuildProperties buildProperties ) {
        if ( buildProperties == null ) {
            log.info( "Build information is missing; release notes are not shown" );
            return null;
        }

        String buildVersion = buildProperties.getVersion();
        String releaseText = buildVersion != null && buildVersion.endsWith( SNAPSHOT_SUFFIX )
                ? buildVersion.substring( 0, buildVersion.length() - SNAPSHOT_SUFFIX.length() )
                : buildVersion;
        Optional< ReleaseVersion > version = ReleaseVersion.parse( releaseText );
        if ( version.isEmpty() ) {
            log.warn( "Build version {} is no release version; release notes are not shown", buildVersion );
            return null;
        }
        log.debug( "Release notes follow installed version {}", version.get() );
        return version.get();
    }

    private @Nullable ReleaseVersion findLastAcknowledged() {
        return acknowledgementRepository.findAll().stream()
                .map( acknowledgement -> ReleaseVersion.parse( acknowledgement.getVersion() ) )
                .flatMap( Optional::stream )
                .max( Comparator.naturalOrder() )
                .orElse( null );
    }

    private boolean isUnacknowledged( ReleaseVersion version, @Nullable ReleaseVersion lastAcknowledged ) {
        if ( version.isNewerThan( requireNonNull( installedVersion ) ) ) {
            return false;
        }
        return lastAcknowledged == null ? version.equals( installedVersion ) : version.isNewerThan( lastAcknowledged );
    }
}
