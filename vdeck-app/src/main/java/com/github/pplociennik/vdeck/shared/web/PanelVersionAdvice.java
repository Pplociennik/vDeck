package com.github.pplociennik.vdeck.shared.web;

import jakarta.annotation.Nullable;
import lombok.extern.log4j.Log4j2;
import org.springframework.boot.info.BuildProperties;
import org.springframework.web.bind.annotation.ControllerAdvice;
import org.springframework.web.bind.annotation.ModelAttribute;

/**
 * Makes the panel version available to every rendered view, because the side menu shows it in its footer and
 * the side menu is embedded on several screens.
 *
 * <p>Like the advice supplying the server status, this one is deliberately not limited by
 * {@code assignableTypes}: it contributes a read-only model attribute owned by no single controller.
 *
 * <p>The version is read once, from {@link BuildProperties} generated by the Maven build, and shown exactly as
 * built, so a development build keeps its {@code -SNAPSHOT} suffix. Without build information - for example
 * when the panel runs from an IDE that did not run the build - the attribute is {@code null} and the footer is
 * not rendered.
 */
@Log4j2
@ControllerAdvice
class PanelVersionAdvice {

    /**
     * Model attribute the side menu footer reads the panel version from.
     */
    static final String PANEL_VERSION_ATTRIBUTE = "panelVersion";

    /**
     * Version of the running panel, or {@code null} when the build did not generate build information.
     */
    private final String panelVersion;

    /**
     * Creates the model contributor and reads the panel version.
     *
     * @param buildProperties
     *         build information of the panel, or {@code null} when the build did not generate it
     */
    PanelVersionAdvice( @Nullable BuildProperties buildProperties ) {
        this.panelVersion = buildProperties == null ? null : buildProperties.getVersion();
        log.debug( "Side menu footer shows panel version {}", panelVersion );
    }

    /**
     * Supplies the version of the running panel.
     *
     * @return version shown in the side menu footer, or {@code null} when it is unknown
     */
    @ModelAttribute( PANEL_VERSION_ATTRIBUTE )
    @Nullable
    String panelVersion() {
        return panelVersion;
    }
}
