package com.github.pplociennik.vdeck.feature.releasenotes.service.impl;

import com.github.pplociennik.vdeck.runtime.installation.ReleaseVersion;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.core.io.Resource;
import org.springframework.core.io.support.PathMatchingResourcePatternResolver;

import java.io.IOException;
import java.io.InputStream;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;
import java.util.Properties;

import static java.nio.charset.StandardCharsets.UTF_8;
import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.catchThrowable;

/**
 * Guards the change list files shipped with the panel, {@code release-notes/<version>.md}. The reader
 * skips a broken file at runtime so the home page keeps working; this test is what keeps such a file out
 * of a build, and what makes sure the version being developed has a file to fill.
 */
class ReleaseNotesFilesTest {

    // =================================================================================================
    // FIELDS
    // =================================================================================================

    /**
     * Build information generated by {@code spring-boot-maven-plugin:build-info} before the tests run.
     */
    private static final String BUILD_INFO = "META-INF/build-info.properties";

    private List< Resource > underTest;

    // =================================================================================================
    // BEFORE METHODS
    // =================================================================================================

    /**
     * Lists the change list files the panel would read.
     *
     * @throws IOException
     *         if the classpath cannot be listed
     */
    @BeforeEach
    void setUp() throws IOException {
        underTest = List.of( new PathMatchingResourcePatternResolver()
                .getResources( ReleaseNotesReader.LOCATION_PATTERN ) );
    }

    // =================================================================================================
    // TESTS
    // =================================================================================================

    /**
     * Verifies that every file is named after a release version and follows the change list format.
     */
    @Test
    void shouldFollowFormat_whenFileIsShipped() {
        // GIVEN
        List< String > problems = new ArrayList<>();

        // WHEN
        for ( Resource resource : underTest ) {
            describeProblem( resource ).ifPresent( problems::add );
        }

        // THEN
        assertThat( underTest ).isNotEmpty();
        assertThat( problems ).isEmpty();
    }

    /**
     * Verifies that the version being built has its change list file, so every change can be described
     * while it is implemented and the release can use the file as its description.
     *
     * @throws IOException
     *         if the build information cannot be read
     */
    @Test
    void shouldContainFile_whenVersionIsBuilt() throws IOException {
        // GIVEN
        ReleaseVersion builtVersion = readBuiltVersion();

        // WHEN
        var versions = underTest.stream()
                .map( resource -> ReleaseNotesReader.versionOf( resource.getFilename() ) )
                .flatMap( Optional::stream )
                .toList();

        // THEN
        assertThat( versions ).contains( builtVersion );
    }

    // =================================================================================================
    // HELPER METHODS
    // =================================================================================================

    private static Optional< String > describeProblem( Resource resource ) {
        Optional< ReleaseVersion > version = ReleaseNotesReader.versionOf( resource.getFilename() );
        if ( version.isEmpty() ) {
            return Optional.of( resource.getFilename() + ": name is not <MAJOR.MINOR.PATCH>.md" );
        }
        Throwable failure = catchThrowable(
                () -> ReleaseNotesParser.parse( version.get(), resource.getContentAsString( UTF_8 ) ) );
        return failure == null ? Optional.empty() : Optional.of( resource.getFilename() + ": " + failure.getMessage() );
    }

    private static ReleaseVersion readBuiltVersion() throws IOException {
        Properties buildInfo = new Properties();
        try ( InputStream input = ReleaseNotesFilesTest.class.getClassLoader().getResourceAsStream( BUILD_INFO ) ) {
            assertThat( input ).as( "%s generated by the Maven build", BUILD_INFO ).isNotNull();
            buildInfo.load( input );
        }
        String version = buildInfo.getProperty( "build.version" ).replace( "-SNAPSHOT", "" );
        return ReleaseVersion.parse( version ).orElseThrow();
    }
}
